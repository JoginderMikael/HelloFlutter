void main(){
  //If statements
  var num = 5;
  if(num == 5){
    print("The number is 5");
  }

  //if/else
  if(num > 5){
    print("The number is greater than 5");
  } else {
    print("The number is less than or equal to 5");
  }

  //else if
  if(num > 5){
    print("The number is greater than 5");
  } else if(num < 5){
    print("The number is less than 5");
  } else {
    print("The number is equal to 5");
  }
}